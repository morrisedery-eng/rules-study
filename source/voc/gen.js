// Build hespeak.js: full-string and word-level niqqud maps for the Hebrew voice.
const fs=require("fs"),D=__dirname;
const MARKS=/[֑-ׇֽֿׁׂׅׄ]/g;
const parse=f=>{const m={};if(!fs.existsSync(f))return m;fs.readFileSync(f,"utf8").split("\n").forEach(l=>{const i=l.indexOf("| ");if(i>0&&!l.startsWith("#"))m[l.slice(0,i)]=l.slice(i+2)});return m};
const full=new Map(),wc={};
const addWords=(p,v)=>{const tp=p.match(/[א-ת]+/g)||[],tv=v.match(/[א-ת֑-ׇ]+/g)||[];
  if(tp.length!==tv.length)throw new Error("token mismatch: "+p);
  tp.forEach((w,i)=>{if(tv[i]===w)return;(wc[w]=wc[w]||{})[tv[i]]=(wc[w][tv[i]]||0)+1})};
for(let d=1;d<=15;d++){const n=String(d).padStart(2,"0"),src=parse(`${D}/src${n}.txt`),voc=parse(`${D}/v${n}.txt`);
  for(const k in voc){const p=src[k],v=voc[k];if(!p||v.replace(MARKS,"")!==p)throw new Error(`bad ${d} ${k}`);
    addWords(p,v);
    // the card lines are "English · Hebrew": keep only the Hebrew side as a phrase
    const pi=p.lastIndexOf(" · "),vi=v.lastIndexOf(" · ");
    const ph=k[0]==="C"&&pi>=0?p.slice(pi+3):p,vh=k[0]==="C"&&vi>=0?v.slice(vi+3):v;
    if(ph.split(" ").length>=2)full.set(ph,vh)}}
// extra fixed phrases (coach, quiz, timer, helper)
const ex=fs.existsSync(`${D}/extra.txt`)?fs.readFileSync(`${D}/extra.txt`,"utf8").split("\n"):[];
ex.forEach(l=>{l=l.trim();if(!l||l.startsWith("#"))return;const v=l,p=v.replace(MARKS,"");addWords(p,v);if(p.split(" ").length>=2)full.set(p,v)});
const words={};let amb=0;
for(const w in wc){const e=Object.entries(wc[w]).sort((a,b)=>b[1]-a[1]),tot=e.reduce((s,x)=>s+x[1],0);
  if(e[0][1]/tot>=0.75)words[w]=e[0][0];else amb++}
const list=[...full.entries()].sort((a,b)=>b[0].length-a[0].length);
const out=`// Generated by voc/gen.js: Hebrew text with full niqqud for the voice (on-screen text is unchanged)\nconst HE_SPEAK=${JSON.stringify(list)};\nconst HE_WORDS=${JSON.stringify(words)};\n`;
fs.writeFileSync(`${D}/../hespeak.js`,out);
console.log(`phrases ${list.length}, words ${Object.keys(words).length}, ambiguous skipped ${amb}, bytes ${out.length}`);
if(process.argv[2]==="amb")for(const w in wc)if(!words[w])console.log(w,JSON.stringify(wc[w]));
